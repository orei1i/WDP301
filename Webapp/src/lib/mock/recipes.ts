export const getFeaturedRecipe = () => RECIPES.find((r) => r.isFeatured) ?? RECIPES[0]!;

export const getRecipeBySlug = (slug: string) => RECIPES.find((r) => r.slug === slug);

/** Naive "related": same recipe type or shared food types, most-viewed first. */
export function getRelatedRecipes(recipe: Recipe, limit = 4) {
  return RECIPES.filter((r) => r.id !== recipe.id)
    .map((r) => ({
      r,
      score: (r.recipeType === recipe.recipeType ? 2 : 0) + r.foodTypes.filter((f) => recipe.foodTypes.includes(f)).length,
    }))
    .sort((a, b) => b.score - a.score || b.r.views - a.r.views)
    .slice(0, limit)
    .map((x) => x.r);
}
